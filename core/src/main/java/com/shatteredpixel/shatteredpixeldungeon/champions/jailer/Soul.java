package com.shatteredpixel.shatteredpixeldungeon.champions.jailer;

import com.shatteredpixel.shatteredpixeldungeon.actors.hero.Hero;
import com.shatteredpixel.shatteredpixeldungeon.actors.hero.HeroClass;
import com.shatteredpixel.shatteredpixeldungeon.items.Item;
import com.shatteredpixel.shatteredpixeldungeon.messages.Messages;
import com.shatteredpixel.shatteredpixeldungeon.scenes.GameScene;
import com.shatteredpixel.shatteredpixeldungeon.sprites.ItemSprite;
import com.shatteredpixel.shatteredpixeldungeon.sprites.ItemSpriteSheet;
import com.shatteredpixel.shatteredpixeldungeon.utils.GLog;

import java.util.ArrayList;

//solo el jailer, straight into the lantern
public class Soul extends Item {

	{
		image = ItemSpriteSheet.SOUL;
		stackable = true;
		dropsDownHeap = true;
		bones = false;
	}

	@Override
	public boolean doPickUp( Hero hero, int pos ) {
		if (hero.heroClass != HeroClass.JAILER){
			GLog.w(Messages.get(Soul.class, "not_jailer"));
			return false;
		}
		GameScene.pickUp(this, pos);
		Damnation.gain(hero, quantity());
		hero.spendAndNext(pickupDelay());
		return true;
	}

	@Override
	public ArrayList<String> actions( Hero hero ) {
		return new ArrayList<>();
	}

	@Override
	public boolean isUpgradable() {
		return false;
	}

	@Override
	public boolean isIdentified() {
		return true;
	}

	@Override
	public ItemSprite.Glowing glowing() {
		return new ItemSprite.Glowing(0x66FF99, 1.5f);
	}
}
