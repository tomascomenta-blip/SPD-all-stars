package com.shatteredpixel.shatteredpixeldungeon.soulknight.finale;

import com.shatteredpixel.shatteredpixeldungeon.actors.Actor;
import com.shatteredpixel.shatteredpixeldungeon.actors.mobs.Mob;
import com.shatteredpixel.shatteredpixeldungeon.soulknight.finale.echo.EchoBoss;

//the world bosses come back through the middle portal as echoes of themselves
public class Echoes {

	public static Mob make( int world ){
		return EchoBoss.forWorld(world);
	}

	//EchoBoss climbs out of the portal on its own
	public static void emerge( Mob m ){
	}

	public static boolean alive( int id ){
		Actor a = Actor.findById(id);
		return a instanceof Mob && ((Mob) a).isAlive();
	}
}
