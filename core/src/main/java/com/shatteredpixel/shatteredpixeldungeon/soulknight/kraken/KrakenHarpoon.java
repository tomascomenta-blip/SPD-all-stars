package com.shatteredpixel.shatteredpixeldungeon.soulknight.kraken;

import com.shatteredpixel.shatteredpixeldungeon.actors.hero.Hero;
import com.shatteredpixel.shatteredpixeldungeon.items.Item;
import com.shatteredpixel.shatteredpixeldungeon.messages.Messages;
import com.shatteredpixel.shatteredpixeldungeon.sprites.ItemSpriteSheet;
import com.shatteredpixel.shatteredpixeldungeon.utils.GLog;

import java.util.ArrayList;

//washes up on deck. carry it into the bow cannon to fire
public class KrakenHarpoon extends Item {

	{
		image = ItemSpriteSheet.KRAKEN_HARPOON;
		stackable = true;
		bones = false;
	}

	@Override
	public ArrayList<String> actions( Hero hero ) {
		return super.actions(hero);
	}

	@Override
	public boolean doPickUp( Hero hero, int pos ) {
		if (super.doPickUp(hero, pos)){
			GLog.i(Messages.get(this, "hint"));
			return true;
		}
		return false;
	}

	@Override
	public boolean isUpgradable() {
		return false;
	}

	@Override
	public boolean isIdentified() {
		return true;
	}
}
