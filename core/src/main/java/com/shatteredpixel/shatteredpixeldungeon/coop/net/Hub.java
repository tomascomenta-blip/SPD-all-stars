package com.shatteredpixel.shatteredpixeldungeon.coop.net;

//The host's side of a game with several guests (star): one Link per guest, made as guests appear.
//A guest keeps its Link across reconnections as long as it is the same running game.
public interface Hub {

	interface Listener {
		//a guest showed up for the first time; the listener must set the link's listener right away
		void onGuest( Link link );
	}

	void setListener( Listener listener );

	void start();

	void close();

}
